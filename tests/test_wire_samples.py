"""
The JSON the server sends, as real samples, checked against frontend/src/api/types.ts (ARCH-8).

This test builds one sample of each payload the frontend reads (a job summary,
a job detail (with its instance and result), a benchmark row) and writes them as a
TypeScript file, frontend/src/api/wireSamples.ts, where each one is declared
`satisfies <its type>`. Two checks keep the sides together:

- Here: the generated text must equal the committed file, so a field added to,
  removed from or renamed in a Python payload fails this test.
- In `npm run typecheck`: `satisfies` fails when a field the type requires is
  missing, and also when a sample has a field the type does not declare, so a
  rename in types.ts fails it too.

After a deliberate change of a payload, run this test with
WIZSAT_RECORD_GOLDEN=1 to rewrite the file, then update types.ts and read the
diff. The timings are zeroed: they are the only values that change between runs.
"""

import json
import os
import unittest
from collections import deque
from pathlib import Path
from typing import Any

from sat_core.environment import run_environment
from sat_core.jobs import execute_job, parse_solve_request
from sat_core.runtime import EVENT_INSTANCE, EVENT_RESULT, EVENT_ROW, RunToken
from sat_web.manager import Job

SAMPLES_FILE = Path(__file__).parent.parent / "frontend" / "src" / "api" / "wireSamples.ts"

HEADER = """\
// Generated by tests/test_wire_samples.py: real payloads of the server, each checked
// against its type in types.ts when `npm run typecheck` runs. Do not edit by hand;
// after a deliberate payload change run that test with WIZSAT_RECORD_GOLDEN=1.
import type { BenchmarkRow, JobDetail, JobSummary, SolveRequest } from "./types";
"""


# Fixed values for the environment of the sample job: the real ones differ per machine.
# The keys come from run_environment(), so a new key raises KeyError here and needs a value.
SAMPLE_ENVIRONMENT = {
    "python_implementation": "CPython",
    "python_version": "3.12.0",
    "os": "Linux 6.8.0 (x86_64)",
    "cpu_model": "Example CPU @ 3.00GHz",
    "cpu_logical_cores": 8,
    "cpu_physical_cores": 4,
    "ram_total_gb": 15.5,
    "wizsat_version": "2.0.0",
    "git_commit": "0000000",
    "git_dirty": False,
}


def sample_environment() -> dict[str, Any]:
    return {key: SAMPLE_ENVIRONMENT[key] for key in run_environment()}


def run_events(kind: str, request: dict[str, Any]) -> list:
    events: list = []
    execute_job(kind, request, None, events.append, RunToken())
    return events


def payload_of(events: list, event_type: str) -> dict[str, Any]:
    return next(event.payload for event in events if event.type == event_type)


def zero_timings(payload: dict[str, Any]) -> None:
    for key in ("encode_seconds", "elapsed"):
        if key in payload:
            payload[key] = 0.0
    if "stats" in payload and "elapsed" in payload["stats"]:
        payload["stats"]["elapsed"] = 0.0


def build_samples() -> dict[str, tuple[str, Any]]:
    """Sample name -> (TypeScript type expression, payload), in the order they are written."""

    request = parse_solve_request({"problem": "sudoku", "params": {"size": 9}, "solver": "cdcl"})
    events = run_events("solve", request)
    instance = payload_of(events, EVENT_INSTANCE)
    result = payload_of(events, EVENT_RESULT)
    zero_timings(instance)
    zero_timings(result)

    job = Job(
        id=7,
        kind="solve",
        title="Sudoku (9x9 manual, 30 givens) (CDCL)",
        status="done",
        request=request,
        created_at="2026-11-19T10:00:00.000+00:00",
        workdir=Path("."),
        started_at="2026-11-19T10:00:00.100+00:00",
        finished_at="2026-11-19T10:00:00.300+00:00",
        progress={"current": 2, "total": 2, "message": "Finished: SAT"},
        instance=instance,
        result=result,
        environment=sample_environment(),
        logs=deque([["10:00:00", "Encoding Sudoku: 9x9 manual, 30 givens"], ["10:00:00", "Finished."]]),
        rev=4,
    )

    bench_events = run_events("benchmark", {"problems": ["n_queens"], "segments": [{"size": 4}], "solvers": ["cdcl"]})
    row = payload_of(bench_events, EVENT_ROW)["row"]
    zero_timings(row)

    return {
        "jobSummary": ("JobSummary", job.summary()),
        # The detail holds the instance, the result and the environment, so they are checked here too. A solve job's
        # request is a SolveRequest; JobDetail types it as a solve and a benchmark request at once.
        "jobDetail": ('Omit<JobDetail, "request"> & { request: SolveRequest }', job.detail()),
        "benchmarkRow": ("BenchmarkRow", row),
    }


def render(samples: dict[str, tuple[str, Any]]) -> str:
    parts = [HEADER]
    for name, (type_expression, payload) in samples.items():
        # JSON is a TypeScript object literal; `satisfies` keeps "done" a literal so it fits a status union.
        parts.append(f"export const {name} = {json.dumps(payload, indent=2)} satisfies {type_expression};\n")
    return "\n".join(parts)


class WireSampleTests(unittest.TestCase):
    def test_the_samples_match_the_committed_typescript_file(self):
        generated = render(build_samples())
        if os.environ.get("WIZSAT_RECORD_GOLDEN") == "1":
            SAMPLES_FILE.write_text(generated, encoding="utf-8", newline="\n")

        committed = SAMPLES_FILE.read_text(encoding="utf-8").replace("\r\n", "\n")
        self.assertEqual(generated, committed, "payloads changed: re-record with WIZSAT_RECORD_GOLDEN=1 and update types.ts")


if __name__ == "__main__":
    unittest.main()
